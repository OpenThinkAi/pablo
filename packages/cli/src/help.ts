/** The usage entries for a verb: each starts at a `  pablo <verb>` line and runs through its indented continuation lines. */
export function usageFor(verb: string): readonly string[] {
  const out: string[] = [];
  let inside = false;
  for (const line of USAGE_LINES) {
    const start = /^  pablo (\S+)/.exec(line);
    if (start !== null) inside = start[1] === verb;
    else if (!/^ {4,}\S/.test(line)) inside = false;
    if (inside) out.push(line);
  }
  return out;
}

/** Flag descriptions from the verb's registry entry, where it has one (positional fields and `project` are left out). */
function registryFlags(verb: string): readonly string[] {
  const entry = VERBS.find((v) => v.name === verb);
  if (entry === undefined) return [];
  const positional = new Set(entry.positionalArgs ?? []);
  const lines: string[] = [];
  for (const [key, schema] of Object.entries(entry.args.shape)) {
    if (key === "project" || positional.has(key)) continue;
    const description = (schema as z.ZodTypeAny).description;
    if (description !== undefined) lines.push(`  --${key}  ${description}`);
  }
  return lines;
}

/** The help for one verb, or `undefined` when `verb` is not a verb. `known` is the verb list (`ALL_VERBS`). */
export function verbHelp(verb: string, known: readonly string[]): string | undefined {
  if (!known.includes(verb)) return undefined;
  const usage = usageFor(verb);
  const lines = [`pablo ${verb}`, "", "Usage:"];
  if (usage.length > 0) lines.push(...usage);
  else lines.push(`  pablo ${verb}  (not implemented yet)`);
  const flags = registryFlags(verb);
  if (flags.length > 0) lines.push("", "Flags:", ...flags);
  lines.push("", "Example:", `  ${VERB_EXAMPLES[verb] ?? `pablo ${verb} --project my-story`}`);
  lines.push("", "Every verb accepts --project <slug> and --json. Full reference: docs/commands.md");
  return lines.join("\n");
}
